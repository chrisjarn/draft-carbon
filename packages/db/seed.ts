// ── Seed ────────────────────────────────────────────────────────────────────

async function seed() {
	console.log("Seeding database...\n");

	// 1. Entities
	const entResult = await db
		.insert(entities)
		.values(ENTITIES)
		.onConflictDoNothing();
	console.log(
		`  entities: ${entResult.count} inserted (${ENTITIES.length} total)`,
	);

	// 2. Carbonites
	const cbResult = await db
		.insert(carbonites)
		.values(CARBONITES)
		.onConflictDoNothing();
	console.log(
		`  carbonites: ${cbResult.count} inserted (${CARBONITES.length} total)`,
	);

	// 3. Hiring needs
	const hnResult = await db
		.insert(hiringNeeds)
		.values(HIRING_NEEDS)
		.onConflictDoNothing();
	console.log(
		`  hiring_needs: ${hnResult.count} inserted (${HIRING_NEEDS.length} total)`,
	);

	// 4. Salary brackets
	const sbResult = await db
		.insert(salaryBrackets)
		.values(SALARY_BRACKETS)
		.onConflictDoNothing();
	console.log(
		`  salary_brackets: ${sbResult.count} inserted (${SALARY_BRACKETS.length} total)`,
	);

	console.log("\nSeed complete.");
	process.exit(0);
}

seed().catch((err) => {
	console.error("Seed failed:", err);
	process.exit(1);
});
